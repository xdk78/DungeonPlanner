def instance_keys(casc, tables: Tables, map_id: int):
    """{English name: {key, ...}} of the areas the client can name inside the instance: its WMOs' area rows and its
    map's AreaTable areas."""
    wdt = tables.maps.get(map_id, {}).get("wdt")
    wmo_ids = set()
    for fid, *_ in placements(casc, wdt) if wdt else []:
        wid, _parts = wmo_parts(casc, fid)
        if wid is not None:
            wmo_ids.add(wid)
    found = {}
    for rid in sorted(tables.wmo_rows):
        key = tables.wmo_rows[rid]["wmo"] in wmo_ids and key_of_row(tables, rid)
        if key:
            found.setdefault(english(tables, key), set()).add(key)
    for aid, a in sorted(tables.areas.items()):
        if a["map"] == map_id and a["parent"] != 0:
            found.setdefault(a["name"].strip(SPACE), set()).add(("area", aid))
    return found


def fdr_samples(slug, plan, d, fdr, fdr_root, casc, instances, keys, log):
    rooms = (fdr.get("rooms") or {}).get(d["key"]) or []
    fmap = ir.floor_map(fdr, fdr_root, d, plan, {}, casc, instances, lambda s: None)
    out = {}
    for room in rooms:
        found = keys.get(room["name"].strip(SPACE))
        if not found:
            log(f"{slug}: room {room['name']!r} matches no area row of the instance; left out")
            continue
        key = min(found)
        for floor, u, v, w, h, _angle in room["boxes"]:
            got = fmap.get(int(floor))
            if not got:
                continue
            pf, fn = got
            x, y = fn(u, v)
            out.setdefault(pf, []).append((key, x, y, max(1.0, w * h)))
    return out


