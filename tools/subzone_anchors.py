def english(tables: Tables, key):
    return (tables.wmo_rows[key[1]]["names"]["enUS"] if key[0] == "wmo" else tables.areas[key[1]]["name"]).strip(SPACE)


def anchors(per_floor, tables: Tables, map_id: int, known):
    """One entry per name the client shows (in English): the samples of every row that shows it, an AreaTable ID (the
    heaviest) and a WMO area ID (the lowest) when rows of that kind show it; `known` adds the instance's other rows of
    the same names."""
    # The instance's own name is the zone text: the addon ignores a sub-zone that reads the same.
    roots = {a["name"].strip(SPACE) for a in tables.areas.values() if a["map"] == map_id and a["parent"] == 0}
    acc, weight_of = {}, {}
    for floor, samples in per_floor.items():
        for key, x, y, weight in samples:
            name = english(tables, key)
            if name in roots:
                continue
            a = acc.setdefault(name, {}).setdefault(floor, [0.0, 0.0, 0.0, 0])
            a[0] += x * weight
            a[1] += y * weight
            a[2] += weight
            a[3] += 1
            weight_of[key] = weight_of.get(key, 0.0) + weight
    floor_weight = {}
    for floors in acc.values():
        for floor, a in floors.items():
            floor_weight[floor] = floor_weight.get(floor, 0.0) + a[2]
    out = []
    for name in sorted(acc):
        floors = acc[name]
        total = sum(a[2] for a in floors.values())
        at = []
        for floor in sorted(floors):
            sx, sy, sw, n = floors[floor]
            x, y = sx / sw, sy / sw
            # An area whose middle is at the map's edge lies mostly beyond the drawn map (the mountains around it).
            if min(x, y, 1 - x, 1 - y) < EDGE:
                continue
            # A small cave floor holds little of an area that covers the land above, but the area is all of that floor.
            if sw >= MIN_SHARE * total or sw >= 0.5 * floor_weight[floor]:
                at.append({"floor": floor, "x": round(x, 4), "y": round(y, 4),
                           "share": round(sw / total, 2), "samples": n})
        keys = {k for k in weight_of if english(tables, k) == name} | known.get(name, set())
        areas = sorted((k for k in keys if k[0] == "area"), key=lambda k: (-weight_of.get(k, 0.0), k[1]))
        wmos = sorted(k[1] for k in keys if k[0] == "wmo")
        entry = {"name": name}
        if areas:
            entry["area"] = areas[0][1]
        if wmos:
            # Rows of one English name may be spelled differently in another language (with an article or without): the client
            # shows whichever row the player stands in, so every spelling counts.
            entry["wmo"] = wmos[0]
            entry["names"] = {}
            for loc in LOCALES[1:]:
                spellings = sorted({tables.wmo_rows[w]["names"][loc].strip(SPACE) for w in wmos
                                    if tables.wmo_rows[w]["names"].get(loc)})
                if spellings:
                    entry["names"][loc] = spellings
        entry["at"] = at
        out.append(entry)
    return out


def preview(game, casc, fdj, instances, plan, per_floor, areas, tables, work: Path):
    """The plan's floor pictures with each sample (a dot) and anchor (a ring and the name), to check by eye."""
    bases = rp.tile_bases(instances, plan)
    for floor in sorted(per_floor):
        got = rp.provider_floor(game, fdj, {}, plan, floor)
        if got:
            img, _source, pins = got
            sx, tx, sy, ty, _mode = rp.align(plan, floor, pins)
        elif floor <= len(bases) and (img := rp.classic_floor(casc, bases[floor - 1])) is not None:
            sx, tx, sy, ty = 1.0, 0.0, 1.0, 0.0
        else:
            continue
        img = img.convert("RGB")
        d = ImageDraw.Draw(img)
        W, H = img.size

        def px(x, y, sx=sx, tx=tx, sy=sy, ty=ty, W=W, H=H):
            return (x * sx + tx) * W, (y * sy + ty) * H

        names = sorted({english(tables, k) for k, *_ in per_floor[floor]})
        colours = {n: ((97 * i) % 200 + 55, (57 * i) % 200 + 55, (151 * i) % 200 + 55) for i, n in enumerate(names)}
        for key, x, y, _w in per_floor[floor]:
            u, v = px(x, y)
            d.ellipse((u - 2, v - 2, u + 2, v + 2), fill=colours[english(tables, key)])
        for a in areas:
            for at in a["at"]:
                if at["floor"] == floor:
                    u, v = px(at["x"], at["y"])
                    d.ellipse((u - 9, v - 9, u + 9, v + 9), outline=colours.get(a["name"], (255, 255, 255)), width=3)
                    d.text((u + 11, v - 6), a["name"], fill=(255, 255, 255))
        work.mkdir(parents=True, exist_ok=True)
        img.save(work / f"subzones-{plan['id']}-{floor}.png")


VECTORS = REPO / "tests" / "fnv1a_vectors.json"


def fnv1a(text: str) -> int:
    """32-bit FNV-1a over the UTF-8 bytes: the hash Data/Subzones.lua (Subzones.Hash) computes in game."""
    h = 0x811C9DC5
    for b in text.encode("utf-8"):
        h = ((h ^ b) * 0x01000193) & 0xFFFFFFFF
    return h


def check_vectors():
    """The test vectors tests/test_subzones.lua checks the Lua hash with: this hash must give the same."""
    for v in json.loads(VECTORS.read_text(encoding="utf-8")):
        if fnv1a(v["text"]) != v["hash"]:
            raise SystemExit(f"fnv1a({v['text']!r}) = {fnv1a(v['text'])}, {VECTORS.name} says {v['hash']}")


def public(entry):
    """An area as it goes into the repository: IDs, the hashes of a WMO area's names in LOCALES order (one, several,
    or false where the client has no name in that language), anchors. No name."""
    out = {"key": f"a{entry['area']}" if "area" in entry else f"w{entry['wmo']}"}
    for field in ("area", "wmo"):
        if field in entry:
            out[field] = entry[field]
    if "wmo" in entry:
        out["hashes"] = []
        for loc in LOCALES:
            spellings = [entry["name"]] if loc == "enUS" else entry["names"].get(loc, [])
            hashes = sorted({fnv1a(s) for s in spellings})
            out["hashes"].append(hashes[0] if len(hashes) == 1 else hashes or False)
    out["at"] = entry["at"]
    return out


def render(doc):
    return json.dumps(doc, indent=1, ensure_ascii=False) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--game", type=Path, help="the game folder that holds Interface/AddOns (e.g. _forever_)")
    ap.add_argument("--work", type=Path, help="scratch folder (the downloaded tables, the names, previews, the log)")
    ap.add_argument("--fdr", type=Path, help="folder holding ForeverDungeonRoutes (default: the game's Interface/AddOns)")
    ap.add_argument("--only", default="", help="comma-separated plan slugs")
    ap.add_argument("--check", action="store_true", help="write nothing; exit 1 when a JSON file would change")
    ap.add_argument("--self-test", action="store_true", help="only check the hash against tests/fnv1a_vectors.json")
    args = ap.parse_args(argv)
    check_vectors()
    if args.self_test:
        print(f"fnv1a matches {VECTORS.name}")
        return
    if not (args.game and args.work):
        ap.error("--game and --work are required")
    work = args.work.resolve()
    if work == REPO or REPO in work.parents:
        raise SystemExit("keep --work outside the repository")
    fdr_root = (args.fdr or args.game / "Interface" / "AddOns").resolve()
    only = {s for s in args.only.split(",") if s}
    lines = []

    def log(s):
        lines.append(s)
        print(s)

    tables = Tables(work)
    casc = ma.Casc(args.game)
    fdj = rp.fdj_maps(args.game)
    fdr = ir.load_fdr(fdr_root)
    plans, instances = rp.load_repo()
    minimaps = json.loads((REPO / "data-src" / "minimaps.json").read_text(encoding="utf-8"))["floors"]
    game_slugs = {e["slug"] for e in minimaps if e.get("planSpace", "provider") == "provider"}
    by_key = {ir.norm_key(instances, d["name"]): d for d in fdr["dungeons"]}
    changed = []

    def drop(path: Path, why: str):
        """A file whose plan has no anchors any more is stale: removed (listed by --check)."""
        if path.exists():
            log(f"{path.name}: stale ({why})")
            changed.append(path.name)
            if not args.check:
                path.unlink()

    for plan in plans:
        slug = plan["id"]
        if only and slug not in only:
            continue
        path = OUT_DIR / f"{slug}.json"
        research = json.loads((REPO / "data-src" / "dungeons" / f"{slug}.json").read_text(encoding="utf-8"))
        map_id = research.get("instanceMapID")
        if not map_id or map_id not in tables.maps:
            drop(path, f"its instance map {map_id} is not in the Map table")
            continue
        known = instance_keys(casc, tables, map_id)
        if slug in game_slugs:
            entries = [dict(e) for e in minimaps if e["slug"] == slug]
            per_floor = game_samples(slug, plan, entries, casc, tables, fdr, fdj, args.game, fdr_root, log)
            src = "game"
        else:
            key = ir.norm_key(instances, plan["instance"]["name"])
            d = by_key.get(key) or next((v for k, v in by_key.items() if len(k) >= 8 and key.startswith(k)), None)
            if not d or not (fdr.get("rooms") or {}).get(d["key"]):
                drop(path, "Forever Dungeon Routes has no rooms for it")
                continue
            per_floor = fdr_samples(slug, plan, d, fdr, fdr_root, casc, instances, known, log)
            src = "fdr"
        areas = anchors(per_floor, tables, map_id, known)
        areas = [a for a in areas if a["at"]]
        if not areas:
            drop(path, "no named area on the plan's floors")
            continue
        preview(args.game, casc, fdj, instances, plan, per_floor, areas, tables, work)
        rows = [public(a) for a in areas]
        # The names stay in the work folder, for checking the previews and the hand fixes by eye.
        (work / "names").mkdir(parents=True, exist_ok=True)
        (work / "names" / f"{slug}.txt").write_text(
            "".join(f"{r['key']}\t{a['name']}\t{json.dumps(a.get('names', {}), ensure_ascii=False)}\n"
                    for r, a in zip(rows, areas)), encoding="utf-8")
        old = json.loads(path.read_text(encoding="utf-8")) if path.exists() else {}
        # Hand fixes stay while their area does.
        keys = {r["key"] for r in rows}
        fixes = {}
        for field in ("overrides", "exclude"):
            fixes[field] = [f for f in old.get(field, []) if f.get("key") in keys]
            for f in old.get(field, []):
                if f.get("key") not in keys:
                    log(f"{slug}: {field} entry for {f.get('key')} dropped: no such area any more")
        doc = {"schema": 1, "slug": slug, "instanceMapID": map_id, "build": BUILD,
               "sources": [s for s in SOURCES if s["id"] in ("wago", src)],
               "position": src, "areas": rows, **fixes}
        text = render(doc)
        log(f"{slug}: {len(areas)} areas ({src})")
        if (path.read_text(encoding="utf-8") if path.exists() else "") != text:
            changed.append(path.name)
            if not args.check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(text, encoding="utf-8", newline="\n")
    if not only:
        slugs = {p["id"] for p in plans}
        for path in sorted(OUT_DIR.glob("*.json")):
            if path.stem not in slugs:
                drop(path, "no recommended plan of that name")
    work.mkdir(parents=True, exist_ok=True)
    (work / "subzone_anchors.log").write_text("\n".join(lines) + "\n", encoding="utf-8")
    if args.check and changed:
        print("would change: " + ", ".join(changed))
        sys.exit(1)
    print(f"{len(changed)} file(s) {'to change' if args.check else 'written'}")


if __name__ == "__main__":
    main()
