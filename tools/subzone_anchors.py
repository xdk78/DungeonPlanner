"""Where each named area of a dungeon lies on the recommended plan's floors: data-src/subzones/<slug>.json.

Inside a dungeon the client gives an addon no position, only the name of the area the player stands in
(GetSubZoneText). This tool works out, offline and read-only, a point on our map for each such area, so the addon can
mark roughly where the player is. Two kinds of area name the client can show (docs/DATA-SOURCES.md, "Sub-zones"):

  * an AreaTable area (terrain chunks carry its ID; a WMO area row may point to it): kept by its AreaTable ID, its name
    read at runtime with C_Map.GetAreaInfo, so it is right in every client language;
  * a WMO area with a name of its own (WMOAreaTable, no AreaTable row): kept by its WMOAreaTable ID with its names in
    the client's languages, since no game function gives that name for an ID; the addon gets only their hashes
    (tools/gen_subzones.lua), never the names.

IDs and names come from the client's tables as wago.tools exports them for one WoW: Forever build (BUILD; downloaded
once into the work folder). Positions:

  * Forever's new dungeons (data-src/minimaps.json floors): from the game's own files on a local install, as
    tools/minimap_art.py reads them: each terrain chunk (33 yards square, its AreaTable ID in its header) and each WMO
    part (its box, placed by the map's MODF; its WMOAreaTable row by WMO ID, name set and group ID) is a weighted
    sample of its area; world yards go to plan space through the floor's plan -> world transform (minimap_art's
    plan_to_world, inverted by a least-squares fit).
  * Classic dungeons: Forever Dungeon Routes' Data/Rooms.lua (MIT; generated by its author from the same client tables:
    WMO area names, WMO part boxes placed by MODF, floors from UiMapAssignment), on the floors whose map is the plan's
    (the old dungeon map, the same 0..1 space). Its room names are English; each is matched to an ID among the WMO area
    rows of the instance's own WMOs and the AreaTable rows of its map, and a room no row names is left out.

An area's anchor on a floor is the weighted middle of its samples there; a floor holds an anchor when at least MIN_SHARE
of the area's samples lie on it. Hand fixes ("overrides", "exclude") in the JSON are kept as they are; the generator
(tools/gen_subzones.lua) applies them.

Usage (from the repository root):
  uv run --script tools/subzone_anchors.py --game "<World of Warcraft>/_forever_" --work <scratch folder> \
      [--fdr <folder holding ForeverDungeonRoutes>] [--only slug,...] [--check]
  then: lua tools/gen_subzones.lua
--fdr defaults to the game's Interface/AddOns. --check writes nothing and exits 1 when a JSON file would change.
"""

