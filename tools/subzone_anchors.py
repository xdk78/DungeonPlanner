def placements(casc, wdt_fid: int):
    """Every WMO placement on the map: [(wmo file ID, (north, west), yaw, name set)]. A map that is one building (most
    classic dungeons) places it in the WDT itself, the others in their terrain tiles' object files."""
    out, seen = [], set()
    files = [casc.read_fid(wdt_fid)] + [ids[1] and casc.read_fid(ids[1]) for ids in ma.World(casc).wdt(wdt_fid).values()]
    for raw in files:
        for tag, d in ma.chunks(raw or b""):
            if tag != "MODF":
                continue
            for k in range(len(d) // 64):
                fid, uid = struct.unpack_from("<II", d, 64 * k)
                if uid in seen:
                    continue
                seen.add(uid)
                x, _h, z = struct.unpack_from("<3f", d, 64 * k + 8)
                yaw = struct.unpack_from("<3f", d, 64 * k + 20)[1]
                name_set = struct.unpack_from("<H", d, 64 * k + 60)[0]
                out.append((fid, (ma.ORIGIN - z, ma.ORIGIN - x), yaw, name_set))
    return out


def wmo_parts(casc, fid: int):
    """A WMO's ID and its parts: [(index, local box (6 floats), group ID for WMOAreaTable)]."""
    raw = casc.read_fid(fid)
    if raw is None:
        return None, []
    wmo_id, boxes, files = None, [], []
    for tag, d in ma.chunks(raw):
        if tag == "MOHD":
            wmo_id = struct.unpack_from("<I", d, 32)[0]
        elif tag == "MOGI":
            boxes = [struct.unpack_from("<6f", d, 32 * k + 4) for k in range(len(d) // 32)]
        elif tag == "GFID":
            files = list(struct.unpack_from(f"<{len(d) // 4}I", d))
    parts = []
    for i, box in enumerate(boxes):
        group_raw = i < len(files) and files[i] and casc.read_fid(files[i])
        gid = -1
        for tag, d in ma.chunks(group_raw or b""):
            if tag == "MOGP":
                gid = struct.unpack_from("<I", d, 56)[0]
                break
        parts.append((i, box, gid))
    return wmo_id, parts


def wmo_samples(casc, tables: Tables, wdt_fid: int, keep, ground):
    """Samples of the WMO parts placed on the map for which keep(wmo file ID, part index) is true. A part whose area row
    names nothing shows the area of the terrain under it (ground(north, west))."""
    out = []
    cache = {}
    for fid, pos, yaw, name_set in placements(casc, wdt_fid):
        if fid not in cache:
            cache[fid] = wmo_parts(casc, fid)
        wmo_id, parts = cache[fid]
        if wmo_id is None:
            continue
        t = math.radians(yaw)
        ct, st = math.cos(t), math.sin(t)
        for i, box, gid in parts:
            if not keep(fid, i):
                continue
            row = tables.by_group.get((wmo_id, name_set, gid))
            if row is None:
                row = tables.by_group.get((wmo_id, name_set, -1))
            lx, ly = (box[0] + box[3]) / 2, (box[1] + box[4]) / 2
            world = (pos[0] - (ct * lx - st * ly), pos[1] - (st * lx + ct * ly))
            key = (row is not None and key_of_row(tables, row)) or ground(*world)
            if key:
                out.append((key, world, max(1.0, (box[3] - box[0]) * (box[4] - box[1]))))
    return out


def terrain_samples(casc, tables: Tables, wdt_fid: int):
    out = []
    for (tx, ty), ids in ma.World(casc).wdt(wdt_fid).items():
        raw = ids[0] and casc.read_fid(ids[0])
        for tag, d in ma.chunks(raw or b""):
            if tag != "MCNK" or len(d) < 0x40:
                continue
            ix, iy = struct.unpack_from("<II", d, 4)
            area = struct.unpack_from("<I", d, 0x34)[0]
            holes = struct.unpack_from("<H", d, 0x3C)[0]
            if area not in tables.areas or holes == 0xFFFF:
                continue
            north = ma.ORIGIN - ty * ma.ADT - (iy + 0.5) * CHUNK
            west = ma.ORIGIN - tx * ma.ADT - (ix + 0.5) * CHUNK
            out.append((("area", area), (north, west), CHUNK * CHUNK))
    return out


def world_to_plan(to_world):
    grid = [(x / 4, y / 4) for x in range(5) for y in range(5)]
    m = ma.affine_fit([to_world(x, y) for x, y in grid], grid)
    return lambda n, w: ma.apply(m, n, w)


def game_samples(slug, plan, entries, casc, tables, fdr, fdj, game, fdr_root, log):
    """{plan floor: [(key, x, y, weight)]} for a dungeon whose floors are in data-src/minimaps.json."""
    claimed = {(e["wmo"], g) for e in entries if e["source"] == "building" for g in e.get("groups") or []}
    terrain = terrain_samples(casc, tables, entries[0]["wdt"])
    cells = {(round(n / CHUNK), round(w / CHUNK)): key for key, (n, w), _ in terrain}

    def ground(n, w):
        return cells.get((round(n / CHUNK), round(w / CHUNK)))

    out = {}
    for e in entries:
        e["_fdr_root"] = str(fdr_root)
        to_world, how = ma.plan_to_world(e, plan, fdr, fdj, game, log)
        if to_world is None:
            log(f"{slug} floor {e['floor']}: left out: {how}")
            continue
        to_plan = world_to_plan(to_world)
        if e["source"] == "terrain":
            samples = terrain + wmo_samples(casc, tables, e["wdt"], lambda fid, i: (fid, i) not in claimed, ground)
        else:
            groups = set(e.get("groups") or [])
            samples = wmo_samples(casc, tables, e["wdt"], lambda fid, i, e=e, groups=groups:
                                  fid == e["wmo"] and (not groups or i in groups), ground)
        kept = out.setdefault(e["floor"], [])
        for key, (n, w), weight in samples:
            x, y = to_plan(n, w)
            if -MARGIN <= x <= 1 + MARGIN and -MARGIN <= y <= 1 + MARGIN:
                kept.append((key, x, y, weight))
        log(f"{slug} floor {e['floor']}: {len(kept)} samples ({how})")
    return out


