COLUMNS = {
    "AreaTable": {"ID", "AreaName_lang", "ContinentID", "ParentAreaID"},
    "Map": {"ID", "WdtFileDataID", "AreaTableID"},
    "WMOAreaTable": {"ID", "AreaName_lang", "WMOID", "NameSetID", "WMOGroupID", "AreaTableID"},
}


def table(work: Path, name: str, locale: str = "enUS"):
    """A table's rows, downloaded once into the work folder. A download whose header lacks the columns used (an error
    page, a changed export) is refused and not kept."""
    path = work / "tables" / BUILD / f"{name}_{locale}.csv"
    if not path.exists():
        path.parent.mkdir(parents=True, exist_ok=True)
        url = WAGO.format(table=name, build=BUILD, locale=locale)
        req = urllib.request.Request(url, headers={"User-Agent": "subzone-anchors"})
        part = path.with_suffix(".part")
        with urllib.request.urlopen(req, timeout=120) as r:
            part.write_bytes(r.read())
        with part.open(encoding="utf-8", newline="") as f:
            header = set(next(csv.reader(f), []))
        if not COLUMNS[name] <= header:
            part.unlink()
            raise SystemExit(f"{url}: not the {name} table (columns missing: {sorted(COLUMNS[name] - header)})")
        part.replace(path)
    with path.open(encoding="utf-8", newline="") as f:
        return list(csv.DictReader(f))


class Tables:
    def __init__(self, work: Path):
        self.areas = {int(r["ID"]): {"name": r["AreaName_lang"], "map": int(r["ContinentID"]),
                                     "parent": int(r["ParentAreaID"])} for r in table(work, "AreaTable")}
        self.maps = {int(r["ID"]): {"wdt": int(r["WdtFileDataID"]), "area": int(r["AreaTableID"])}
                     for r in table(work, "Map")}
        self.wmo_rows = {}
        for locale in LOCALES:
            for r in table(work, "WMOAreaTable", locale):
                row = self.wmo_rows.setdefault(int(r["ID"]), {
                    "wmo": int(r["WMOID"]), "nameSet": int(r["NameSetID"]), "group": int(r["WMOGroupID"]),
                    "area": int(r["AreaTableID"]), "names": {}})
                if r["AreaName_lang"]:
                    row["names"][locale] = r["AreaName_lang"]
        self.by_group = {(r["wmo"], r["nameSet"], r["group"]): i for i, r in self.wmo_rows.items()}


def key_of_row(tables: Tables, row_id: int):
    """The key the client shows for a WMO area row: its own name ("wmo"), else its AreaTable area ("area"), or None."""
    row = tables.wmo_rows[row_id]
    if row["names"].get("enUS"):
        return ("wmo", row_id)
    if row["area"] > 0 and row["area"] in tables.areas:
        return ("area", row["area"])
    return None


